export const INDIA_STATES = Object.keys(INDIA_LOCATIONS);

const STATE_ALIASES = {
  "National Capital Territory of Delhi": "Delhi",
  "NCT of Delhi": "Delhi",
  Orissa: "Odisha",
  Pondicherry: "Puducherry",
  "Andaman & Nicobar Islands": "Andaman and Nicobar Islands",
  "Dadra and Nagar Haveli": "Dadra and Nagar Haveli and Daman and Diu",
  "Daman and Diu": "Dadra and Nagar Haveli and Daman and Diu",
};

export function normalizeIndianState(value) {
  const state = String(value || "").trim();
  return (
    STATE_ALIASES[state] ||
    INDIA_STATES.find((item) => item.toLowerCase() === state.toLowerCase()) ||
    ""
  );
}

export function citiesFor(state, currentCity = "") {
  const cities = INDIA_LOCATIONS[state] || [];
  const city = String(currentCity || "").trim();
  return city &&
    !cities.some((item) => item.toLowerCase() === city.toLowerCase())
    ? [city, ...cities]
    : cities;
}
